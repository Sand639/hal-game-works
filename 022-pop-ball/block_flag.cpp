/*******************************************************************************
* コンストラクタ
*******************************************************************************/
Flag::Flag()
{
	//色設定
	m_col = { 1.0f,0.0f,0.0f,1.0f };

	//モデルを読み込み
	m_Models[0] = ModelLoad("asset/model/flag.fbx");
}

/*******************************************************************************
* 初期化処理
*******************************************************************************/
void Flag::Init()
{
	//サイズ設定
	s = XMMatrixScaling(1.0f, 1.0f, 1.0f);

	//回転設定
	r = XMMatrixRotationY(XMConvertToRadians(30));

	//座標設定
	t = XMMatrixTranslation(0.3f, 0.5f, 0.3f);

}

/*******************************************************************************
* 更新処理
*******************************************************************************/
void Flag::Update()
{

}

/*******************************************************************************
* 描画処理
*******************************************************************************/
void Flag::Draw(const XMMATRIX& MtxWorld)
{
	DrawCube(MtxWorld);

	XMMATRIX modelWorldMatrix;
	modelWorldMatrix = s * r * t;

	ModelDraw(m_Models[0], modelWorldMatrix * MtxWorld);

}

