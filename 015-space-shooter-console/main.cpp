/*******************************************************************************
* インクルードファイル
*******************************************************************************/
#include <time.h>		//時間ヘッダー
#include "conioex.h"	//コンソール系ヘッダー
#include "screen.h"		//画面変更ヘッダー
#include "Scene.h"		//シーン遷移ヘッダー

/*******************************************************************************
* マクロ定義
*******************************************************************************/
#define FPS			(60)			//1秒あたりの描画頻度を定義する
#define INTERVAL	(1000 / FPS)	//描画間隔(ミリ秒)を定義する

/*******************************************************************************
* プロトタイプ宣言
*******************************************************************************/

//ゲームループ
void Init(void);	//初期化
void Uninit(void);	//終了処理

/*******************************************************************************
* グローバル変数
*******************************************************************************/
int clearFlag = 0;	//クリアフラグ

/*******************************************************************************
* メモ
*******************************************************************************/
/*時間がなくてメモが書ききれてないところがあります
　基本的に.cppにインクルードされている.hをたどっていけば概要がわかります*/

/*******************************************************************************
* メイン関数
*******************************************************************************/
int main(void)
{
	Init();		//初期化関数

	DWORD LastTime = timeGetTime();		//前回の経過時間

	SceneInit();	//ゲーム初期化処理

	//ゲームループ
	while (1)
	{
		DWORD NewTime = timeGetTime();	//現在の時刻

		//待機時間を経過したら
		if (NewTime >= LastTime + INTERVAL)
		{
			SceneUpdate();		// ゲーム更新処理


			SceneDraw();		// ゲーム描画処理


			CheckScene();		//移行先シーンがあるかをチェックする

			LastTime = NewTime;	//前回の時間を現在の時間で更新する
		}

	}

	Uninit();	//終了処理関数

	// キー入力待ち
	rewind(stdin);		// ←キー入力情報をクリアする
	(void)getchar();	// キー入力待ち

	/* 終了 */
	return 0;
}


/*******************************************************************************
*初期化関数
*******************************************************************************/
void Init(void)
{
	srand((unsigned int)time(NULL));	//乱数をシャッフルする

	ScreenInit();	//スクリーンのサイズ変更
}


/*******************************************************************************
*終了処理関数
*******************************************************************************/
void Uninit()
{
	ScreenUninit();		//スクリーン設定を元に戻す
}

/*******************************************************************************
*floatをintに四捨五入
*******************************************************************************/
int floatToInt(float f)
{
	return (int)(f + 0.5f);
}

/*******************************************************************************
*クリアフラグのセット関数
*******************************************************************************/
void SetClearFlag(int flag)
{
	clearFlag = flag;
}

/*******************************************************************************
*クリアフラグのゲット関数
*******************************************************************************/
int GetClearFlag(void)
{
	return clearFlag;
}
